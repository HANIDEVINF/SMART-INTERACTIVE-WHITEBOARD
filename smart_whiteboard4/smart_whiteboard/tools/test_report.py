"""Runs the test-suite and writes docs/TEST_RESULTS.md (per-module counts + every test name).

Run from the project root:   python -m tools.test_report
"""
from __future__ import annotations

import os
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

WHAT = {
    "test_detection": "HSV conversion, thresholding, morphology, connected components, centroid (synthetic images, cross-checked with OpenCV)",
    "test_tracking": "exponential smoothing, jump rejection, pointer-lost handling",
    "test_calibration": "homography (DLT), calibration validation, JSON persistence, invalid / degenerate calibrations",
    "test_mapping": "camera -> board -> canvas coordinate mapping, boundaries",
    "test_vision_pipeline": "detect -> track -> map chain against ground truth, fake camera",
    "test_drawing": "drawing primitives, tools, undo / redo, background image",
    "test_remote": "Next / Previous key mapping, debounce, auto-repeat, key log, event filter",
    "test_interaction": "dwell selector, interaction engine (modes), menu tree and layout",
    "test_view": "image zoom / pan transform",
    "test_lesson": "lesson model, JSON, page session, page-control geometry",
    "test_session": "save / load session files, damaged files",
    "test_gui": "main window, dashboard, whiteboard widgets, navigation, reset",
    "test_gui_vision": "camera + vision integrated in the GUI (fake webcam), calibration page, settings page",
    "test_gui_interaction": "remote keys, menus, modes, pointer drawing, zoom / pan, sessions, key diagnostics",
    "test_gui_teaching": "teaching editor, presenting, page navigation, annotations, interface settings",
    "test_camera_live": "REAL webcam (skipped when no camera is available)",
}


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        xml_path = Path(tmp) / "r.xml"
        env = dict(os.environ, QT_QPA_PLATFORM=os.environ.get("QT_QPA_PLATFORM", "offscreen"))
        proc = subprocess.run([sys.executable, "-m", "pytest", "tests", "-q", f"--junitxml={xml_path}"], cwd=ROOT,
                              env=env, capture_output=True, text=True)
        tree = ET.parse(xml_path)
    stats = defaultdict(lambda: {"passed": 0, "failed": 0, "skipped": 0, "names": []})
    for case in tree.iter("testcase"):
        module = case.get("classname", "").split(".")[-1]
        st = "failed" if case.find("failure") is not None or case.find("error") is not None else \
            "skipped" if case.find("skipped") is not None else "passed"
        stats[module][st] += 1
        stats[module]["names"].append((case.get("name", ""), st))
    total = {k: sum(s[k] for s in stats.values()) for k in ("passed", "failed", "skipped")}
    out = [f"# Test results", "",
           f"Generated by `python -m tools.test_report` on {datetime.now():%Y-%m-%d %H:%M} - Python {platform.python_version()}, "
           f"{platform.system()}, headless Qt (offscreen).", "",
           f"**{total['passed']} passed, {total['failed']} failed, {total['skipped']} skipped** "
           "(skipped = tests that need a real webcam; run them on the laptop with "
           "`python -m pytest tests\\test_camera_live.py -s -v`).", "",
           "| Module | Passed | Failed | Skipped | Covers |", "|---|---|---|---|---|"]
    for m in sorted(stats):
        s = stats[m]
        out.append(f"| `{m}` | {s['passed']} | {s['failed']} | {s['skipped']} | {WHAT.get(m, '')} |")
    out += ["", "## Every test", ""]
    for m in sorted(stats):
        out.append(f"### {m}")
        for name, st in stats[m]["names"]:
            out.append(f"- {'ok' if st == 'passed' else st.upper()}: `{name}`")
        out.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "TEST_RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print(proc.stdout.strip().splitlines()[-1])
    return 0 if total["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
